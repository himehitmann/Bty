import type { Product } from "./model";

type ShadeEntry = readonly [id: string, name: string, barcode?: string];

function officialProduct(
  handle: string,
  brand: "dasique" | "TIRTIR",
  name: string,
  imageUrl: string,
  makeupKind: NonNullable<Product["makeupKind"]>,
  details: Pick<Product, "barcode" | "finish" | "size"> & { directions?: string; declaredVeganAndCrueltyFree?: boolean },
  shades?: readonly ShadeEntry[],
): Product {
  const host = brand === "dasique" ? "dasique.com" : "tirtir.global";
  const manufacturerUrl = `https://${host}/products/${handle}`;
  const { directions, declaredVeganAndCrueltyFree, ...specifications } = details;
  const evidence = { source: "manufacturer", url: manufacturerUrl } as const;

  return {
    id: `manufacturer-${brand.toLowerCase()}-${handle}`,
    name,
    brand,
    category: "maquillage",
    source: "manufacturer",
    ingredients: "",
    imageUrl,
    manufacturerUrl,
    makeupKind,
    makeupEffect: "tinted",
    ...specifications,
    usageInstructions: directions ? { ...evidence, text: directions } : undefined,
    claims: declaredVeganAndCrueltyFree ? { vegan: evidence, crueltyFree: evidence } : undefined,
    variants: shades?.map(([id, name, barcode]) => ({
      id,
      name,
      barcode,
      sourceUrl: `${manufacturerUrl}?variant=${id}`,
    })),
  };
}

