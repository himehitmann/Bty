import type { Product } from "./model";

type VariantEntry = readonly [id: string, name: string, barcode?: string, shadeHex?: string];

function officialProduct(
  key: string,
  name: string,
  brand: string,
  manufacturerUrl: string,
  imageUrl: string,
  makeupKind: NonNullable<Product["makeupKind"]>,
  makeupEffect: NonNullable<Product["makeupEffect"]>,
  entries: readonly VariantEntry[],
): Product {
  return {
    id: `manufacturer-${key}`,
    name,
    brand,
    category: "maquillage",
    ingredients: "",
    source: "manufacturer",
    manufacturerUrl,
    imageUrl,
    makeupKind,
    makeupEffect,
    variants: entries.map(([id, name, barcode, shadeHex]) => ({
      id,
      name,
      sourceUrl: /^\d+$/.test(id) ? `${manufacturerUrl}?variant=${id}` : manufacturerUrl,
      barcode,
      shadeHex,
      shadeApproximate: shadeHex ? true : undefined,
    })),
  };
}

function medicubeProduct(handle: string, name: string, imageUrl: string): Product {
  return {
    id: `manufacturer-medicube-${handle}`,
    name,
    brand: "Medicube",
    category: "soin",
    ingredients: "",
    source: "manufacturer",
    manufacturerUrl: `https://medicube.us/products/${handle}`,
    imageUrl,
  };
}

