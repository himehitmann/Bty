import type { Product } from "./model";

const stores = {
  romand: { name: "rom&nd", origin: "https://romandbeauty.com" },
  clio: { name: "CLIO", origin: "https://clubclio.shop" },
};

type ShadeEntry = readonly [id: string, name: string, photo: string, barcode?: string];

function makeupProduct(
  store: keyof typeof stores,
  handle: string,
  name: string,
  imageUrl: string,
  makeupKind: NonNullable<Product["makeupKind"]>,
  directions: string,
  shades: readonly ShadeEntry[],
  details?: Pick<Product, "finish" | "size">,
): Product {
  const brand = stores[store];
  const manufacturerUrl = `${brand.origin}/products/${handle}`;
  const imageDirectory = imageUrl.slice(0, imageUrl.lastIndexOf("/") + 1);
  return {
    id: `manufacturer-${store}-${handle.replace(/^clio-/, "")}`,
    name,
    brand: brand.name,
    category: "maquillage",
    source: "manufacturer",
    manufacturerUrl,
    imageUrl,
    ingredients: "",
    usageInstructions: { text: directions, source: "manufacturer", url: manufacturerUrl },
    makeupKind,
    makeupEffect: "tinted",
    ...details,
    variants: shades.map(([id, name, photo, barcode]) => ({
      id,
      name,
      sourceUrl: `${manufacturerUrl}?variant=${id}`,
      imageUrl: `${imageDirectory}${photo}&width=480`,
      barcode,
    })),
  };
}

